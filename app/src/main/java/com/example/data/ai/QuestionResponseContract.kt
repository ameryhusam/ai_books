package com.example.data.ai

import com.example.model.QuestionDifficulty
import com.example.model.QuestionType
import kotlinx.serialization.json.JsonObject
import kotlinx.serialization.json.JsonPrimitive
import kotlinx.serialization.json.buildJsonObject
import kotlinx.serialization.json.put
import kotlinx.serialization.json.putJsonArray
import kotlinx.serialization.json.putJsonObject

/**
 * The single provider-facing contract for generated questions.
 *
 * Its persisted content fields deliberately mirror the question content stored by
 * QuestionEntity. Lesson/workspace identity, IDs, fingerprints and audit metadata
 * are supplied by the application and must never be generated by the model.
 */
object QuestionResponseContract {
    val schemaJson: String by lazy { buildSchema().toString() }

    val defaultTypeIds: List<String> = listOf(
        QuestionType.MCQ.id,
        QuestionType.TRUE_FALSE.id,
        QuestionType.SHORT_ANSWER.id
    )

    fun effectiveTypes(selectedTypeIds: List<String>): List<QuestionType> {
        val requested = selectedTypeIds.toSet().ifEmpty { defaultTypeIds.toSet() }
        return QuestionType.entries.filter { it.id in requested }
    }

    fun expectedDistribution(questionCount: Int, selectedTypeIds: List<String>): Map<String, Int> {
        val types = effectiveTypes(selectedTypeIds)
        require(questionCount > 0) { "يجب أن يكون عدد الأسئلة أكبر من صفر." }
        require(types.isNotEmpty()) { "يجب اختيار نوع سؤال واحد على الأقل." }
        require(types.size <= questionCount) {
            "عدد أنواع الأسئلة المختارة أكبر من العدد الإجمالي المطلوب."
        }
        val base = questionCount / types.size
        val remainder = questionCount % types.size
        return types.mapIndexed { index, type ->
            type.id to (base + if (index < remainder) 1 else 0)
        }.toMap()
    }

    private fun buildSchema(): JsonObject = buildJsonObject {
        put("type", "object")
        putJsonObject("properties") {
            putJsonObject("questions") {
                put("type", "array")
                putJsonObject("items") {
                    put("type", "object")
                    putJsonObject("properties") {
                        putJsonObject("type") {
                            put("type", "string")
                            putJsonArray("enum") {
                                QuestionType.entries.forEach { add(JsonPrimitive(it.id)) }
                            }
                        }
                        putJsonObject("conceptTag") { put("type", "string") }
                        putJsonObject("prompt") { put("type", "string") }
                        putJsonObject("options") {
                            put("type", "array")
                            putJsonObject("items") { put("type", "string") }
                        }
                        putJsonObject("correctAnswer") { put("type", "string") }
                        putJsonObject("rationale") { put("type", "string") }
                        putJsonObject("difficulty") {
                            put("type", "string")
                            putJsonArray("enum") {
                                QuestionDifficulty.entries.forEach { add(JsonPrimitive(it.id)) }
                            }
                        }
                        putJsonObject("sourcePages") { put("type", "string") }
                    }
                    putJsonArray("required") {
                        add(JsonPrimitive("type"))
                        add(JsonPrimitive("prompt"))
                        add(JsonPrimitive("options"))
                        add(JsonPrimitive("correctAnswer"))
                        add(JsonPrimitive("difficulty"))
                    }
                    put("additionalProperties", false)
                }
            }
        }
        putJsonArray("required") { add(JsonPrimitive("questions")) }
        put("additionalProperties", false)
    }
}
